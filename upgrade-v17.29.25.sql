-- Jira Interno TROBBU v17.29.25
-- Helpdesk Live Data refactor: monotonic revision clock + atomic snapshot + resilient Broadcast.

begin;

-- A tiny, non-sensitive per-workspace revision clock. It carries no ticket data or
-- aggregate counters, so any workspace member may observe it safely. Its purpose is
-- to let clients know with certainty whether their local Helpdesk snapshot is current.
create table if not exists public.helpdesk_live_state (
  workspace_id uuid primary key references public.workspaces(id) on delete cascade,
  revision bigint not null default 0 check (revision >= 0),
  max_updated_at timestamptz,
  changed_at timestamptz not null default now()
);

alter table public.helpdesk_live_state enable row level security;
revoke all on table public.helpdesk_live_state from anon;
revoke all on table public.helpdesk_live_state from authenticated;
grant select on table public.helpdesk_live_state to authenticated;

drop policy if exists helpdesk_live_state_select on public.helpdesk_live_state;
create policy helpdesk_live_state_select
on public.helpdesk_live_state
for select
to authenticated
using (private.is_workspace_member(workspace_id));

create index if not exists ix_helpdesk_live_state_changed
  on public.helpdesk_live_state(changed_at desc);

-- Backfill one clock row for every workspace that already has Helpdesk data.
insert into public.helpdesk_live_state(workspace_id,revision,max_updated_at,changed_at)
select workspace_id,1,max(updated_at),clock_timestamp()
from public.helpdesk_tickets
group by workspace_id
on conflict (workspace_id) do nothing;

-- Increment the workspace revision once for every durable ticket mutation. Trigger
-- ordering is deliberate: trg_80 runs before the existing trg_90 Broadcast trigger,
-- so every Broadcast can carry the exact revision produced by the same transaction.
create or replace function private.bump_helpdesk_live_state()
returns trigger
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_workspace uuid;
  v_changed timestamptz;
begin
  if tg_op='DELETE' then
    v_workspace:=old.workspace_id;
    v_changed:=clock_timestamp();
  else
    v_workspace:=new.workspace_id;
    v_changed:=coalesce(new.updated_at,clock_timestamp());
  end if;

  insert into public.helpdesk_live_state(workspace_id,revision,max_updated_at,changed_at)
  values(v_workspace,1,v_changed,clock_timestamp())
  on conflict (workspace_id) do update
  set revision=public.helpdesk_live_state.revision+1,
      max_updated_at=greatest(public.helpdesk_live_state.max_updated_at,excluded.max_updated_at),
      changed_at=clock_timestamp();

  if tg_op='DELETE' then return old; end if;
  return new;
end
$function$;
revoke all on function private.bump_helpdesk_live_state() from public,anon,authenticated;

drop trigger if exists trg_80_helpdesk_live_state on public.helpdesk_tickets;
create trigger trg_80_helpdesk_live_state
after insert or update or delete on public.helpdesk_tickets
for each row execute function private.bump_helpdesk_live_state();

-- Broadcast now carries the monotonic revision generated by trg_80. The payload
-- still contains the changed row for instant UX, while revision is used only for
-- ordering/deduplication and automatic recovery when a message is missed.
create or replace function private.broadcast_helpdesk_ticket_change()
returns trigger
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_row jsonb;
  v_workspace uuid;
  v_ticket uuid;
  v_operation text:=lower(tg_op);
  v_payload jsonb;
  v_requester uuid;
  v_assignee uuid;
  v_old_assignee uuid;
  v_touch_only boolean:=false;
  v_revision bigint:=0;
begin
  if tg_op='DELETE' then
    v_row:=to_jsonb(old);
    v_workspace:=old.workspace_id;
    v_ticket:=old.id;
    v_requester:=old.requester_user_id;
    v_assignee:=old.assigned_to;
    v_old_assignee:=old.assigned_to;
  else
    v_row:=to_jsonb(new);
    v_workspace:=new.workspace_id;
    v_ticket:=new.id;
    v_requester:=new.requester_user_id;
    v_assignee:=new.assigned_to;
    v_old_assignee:=case when tg_op='UPDATE' then old.assigned_to else null end;
    if tg_op='UPDATE' then
      v_touch_only := (to_jsonb(new)-'updated_at') = (to_jsonb(old)-'updated_at');
    end if;
  end if;

  select s.revision into v_revision
  from public.helpdesk_live_state s
  where s.workspace_id=v_workspace;
  v_revision:=coalesce(v_revision,0);

  v_payload:=jsonb_build_object(
    'workspace_id',v_workspace,
    'ticket_id',v_ticket,
    'entity','ticket',
    'operation',v_operation,
    'row',v_row,
    'touch_only',v_touch_only,
    'revision',v_revision,
    'changed_at',clock_timestamp()
  );

  perform realtime.send(v_payload,'helpdesk_changed','workspace:'||v_workspace::text||':helpdesk',true);

  if not v_touch_only then
    perform realtime.send(v_payload,'helpdesk_changed','helpdesk-ticket:'||v_ticket::text,true);
  end if;

  if v_requester is not null then
    perform realtime.send(v_payload,'helpdesk_changed','user:'||v_requester::text||':helpdesk',true);
  end if;

  if v_assignee is not null and v_assignee is distinct from v_requester then
    perform realtime.send(v_payload,'helpdesk_changed','user:'||v_assignee::text||':helpdesk',true);
  end if;

  if tg_op='UPDATE'
     and v_old_assignee is not null
     and v_old_assignee is distinct from v_assignee
     and v_old_assignee is distinct from v_requester then
    perform realtime.send(
      jsonb_build_object(
        'workspace_id',v_workspace,
        'ticket_id',v_ticket,
        'entity','ticket_scope',
        'operation','reconcile',
        'revision',v_revision,
        'changed_at',clock_timestamp()
      ),
      'helpdesk_changed',
      'user:'||v_old_assignee::text||':helpdesk',
      true
    );
  end if;

  if tg_op='DELETE' then return old; end if;
  return new;
end
$function$;
revoke all on function private.broadcast_helpdesk_ticket_change() from public,anon,authenticated;

-- Small RLS-aware digest used for health checks. Counts always reflect exactly the
-- rows the caller may see, while revision comes from the non-sensitive workspace clock.
create or replace function public.get_helpdesk_watermark(p_workspace uuid)
returns jsonb
language plpgsql
stable
security invoker
set search_path='public','pg_temp'
as $function$
declare
  v_uid uuid:=(select auth.uid());
  v_revision bigint:=0;
  v_total bigint:=0;
  v_max_updated timestamptz;
  v_created bigint:=0;
  v_review bigint:=0;
  v_attended bigint:=0;
  v_closed bigint:=0;
  v_pending_requirements bigint:=0;
  v_approved_requirements bigint:=0;
  v_rejected_requirements bigint:=0;
  v_overdue bigint:=0;
begin
  if v_uid is null then raise exception 'Authentication required'; end if;
  if p_workspace is null then raise exception 'workspace_id is required'; end if;
  if not private.is_workspace_member(p_workspace) then raise exception 'Workspace access required'; end if;

  select coalesce(s.revision,0) into v_revision
  from public.helpdesk_live_state s
  where s.workspace_id=p_workspace;

  select
    count(*),max(updated_at),
    count(*) filter(where coalesce(category,'') not in ('module','feature','new_requirement') and status='created'),
    count(*) filter(where coalesce(category,'') not in ('module','feature','new_requirement') and status='review'),
    count(*) filter(where coalesce(category,'') not in ('module','feature','new_requirement') and status='attended'),
    count(*) filter(where coalesce(category,'') not in ('module','feature','new_requirement') and status='closed'),
    count(*) filter(where category in ('module','feature','new_requirement') and coalesce(proposal_status,'pending')='pending'),
    count(*) filter(where category in ('module','feature','new_requirement') and proposal_status='accepted_backlog'),
    count(*) filter(where category in ('module','feature','new_requirement') and proposal_status='rejected'),
    count(*) filter(where coalesce(category,'') not in ('module','feature','new_requirement') and due_at is not null and status<>'closed' and due_at<now())
  into v_total,v_max_updated,v_created,v_review,v_attended,v_closed,
       v_pending_requirements,v_approved_requirements,v_rejected_requirements,v_overdue
  from public.helpdesk_tickets
  where workspace_id=p_workspace;

  return jsonb_build_object(
    'revision',v_revision,
    'total',v_total,
    'max_updated_at',v_max_updated,
    'created',v_created,'review',v_review,'attended',v_attended,'closed',v_closed,
    'pending_requirements',v_pending_requirements,
    'approved_requirements',v_approved_requirements,
    'rejected_requirements',v_rejected_requirements,
    'overdue',v_overdue,
    'generated_at',clock_timestamp()
  );
end
$function$;
revoke all on function public.get_helpdesk_watermark(uuid) from public,anon;
grant execute on function public.get_helpdesk_watermark(uuid) to authenticated;

-- Atomic RLS-aware snapshot. Rows, counters and revision are returned by one database
-- statement, avoiding client-side races between a list query and a second counter query.
create or replace function public.get_helpdesk_live_snapshot(p_workspace uuid)
returns jsonb
language sql
stable
security invoker
set search_path='public','pg_temp'
as $function$
  with visible as materialized (
    select h.*
    from public.helpdesk_tickets h
    where h.workspace_id=p_workspace
  ), stats as (
    select
      count(*)::bigint as total,
      max(updated_at) as max_updated_at,
      count(*) filter(where coalesce(category,'') not in ('module','feature','new_requirement') and status='created')::bigint as created,
      count(*) filter(where coalesce(category,'') not in ('module','feature','new_requirement') and status='review')::bigint as review,
      count(*) filter(where coalesce(category,'') not in ('module','feature','new_requirement') and status='attended')::bigint as attended,
      count(*) filter(where coalesce(category,'') not in ('module','feature','new_requirement') and status='closed')::bigint as closed,
      count(*) filter(where category in ('module','feature','new_requirement') and coalesce(proposal_status,'pending')='pending')::bigint as pending_requirements,
      count(*) filter(where category in ('module','feature','new_requirement') and proposal_status='accepted_backlog')::bigint as approved_requirements,
      count(*) filter(where category in ('module','feature','new_requirement') and proposal_status='rejected')::bigint as rejected_requirements,
      count(*) filter(where coalesce(category,'') not in ('module','feature','new_requirement') and due_at is not null and status<>'closed' and due_at<now())::bigint as overdue
    from visible
  )
  select jsonb_build_object(
    'revision',coalesce((select revision from public.helpdesk_live_state where workspace_id=p_workspace),0),
    'rows',coalesce((select jsonb_agg(to_jsonb(v) order by v.created_at desc,v.id) from visible v),'[]'::jsonb),
    'total',s.total,
    'max_updated_at',s.max_updated_at,
    'created',s.created,'review',s.review,'attended',s.attended,'closed',s.closed,
    'pending_requirements',s.pending_requirements,
    'approved_requirements',s.approved_requirements,
    'rejected_requirements',s.rejected_requirements,
    'overdue',s.overdue,
    'generated_at',clock_timestamp()
  )
  from stats s
  where (select auth.uid()) is not null
    and private.is_workspace_member(p_workspace)
$function$;
revoke all on function public.get_helpdesk_live_snapshot(uuid) from public,anon;
grant execute on function public.get_helpdesk_live_snapshot(uuid) to authenticated;

-- Postgres Changes on this tiny revision row is a secondary loss detector. Broadcast
-- remains the fast path; this signal only triggers silent recovery if Broadcast is missed.
do $block$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname='supabase_realtime' and schemaname='public' and tablename='helpdesk_live_state'
  ) then
    alter publication supabase_realtime add table public.helpdesk_live_state;
  end if;
end
$block$;

analyze public.helpdesk_live_state;
analyze public.helpdesk_tickets;
notify pgrst,'reload schema';

commit;

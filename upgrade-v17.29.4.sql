create or replace function private.dispatch_notification_web_push()
returns trigger
language plpgsql
security definer
set search_path=''
as $$
declare
  v_token text;
begin
  if not exists(
    select 1 from public.web_push_subscriptions s
    where s.workspace_id=new.workspace_id
      and s.user_id=new.user_id
      and s.disabled_at is null
  ) then
    return new;
  end if;

  select s.decrypted_secret into v_token
  from vault.decrypted_secrets s
  where s.name='jira_notification_cron_token_'||replace(new.workspace_id::text,'-','')
  limit 1;

  if coalesce(v_token,'')='' then return new; end if;

  perform net.http_post(
    url := 'https://prweelxfuvbsdsxfopuh.supabase.co/functions/v1/jira-web-push',
    headers := jsonb_build_object(
      'Content-Type','application/json',
      'x-notification-cron-token',v_token
    ),
    body := jsonb_build_object(
      'notification_id',new.id,
      'workspace_id',new.workspace_id,
      'user_id',new.user_id
    ),
    timeout_milliseconds := 10000
  );
  return new;
end;
$$;
revoke all on function private.dispatch_notification_web_push() from public, anon, authenticated;

drop trigger if exists trg_notification_web_push on public.notifications;
create trigger trg_notification_web_push
after insert on public.notifications
for each row execute function private.dispatch_notification_web_push();

commit;

  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  endpoint text not null,
  p256dh text not null,
  auth_key text not null,
  expiration_time bigint,
  locale text not null default 'es' check (locale in ('es','en')),
  user_agent text,
  platform text,
  device_label text,
  sound_enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_success_at timestamptz,
  last_failure_at timestamptz,
  failure_count integer not null default 0,
  disabled_at timestamptz,
  unique(workspace_id,user_id,endpoint)
);
create index if not exists ix_web_push_subscriptions_user_active
  on public.web_push_subscriptions(workspace_id,user_id,disabled_at);
create index if not exists ix_web_push_subscriptions_user on public.web_push_subscriptions(user_id);
alter table public.web_push_subscriptions enable row level security;
revoke all on table public.web_push_subscriptions from anon, authenticated;
grant select,insert,update,delete on table public.web_push_subscriptions to service_role;
drop policy if exists web_push_subscriptions_select_own on public.web_push_subscriptions;
create policy web_push_subscriptions_select_own on public.web_push_subscriptions
for select to authenticated
using (user_id=(select auth.uid()) and private.is_workspace_member(workspace_id));
drop policy if exists web_push_subscriptions_insert_own on public.web_push_subscriptions;
create policy web_push_subscriptions_insert_own on public.web_push_subscriptions
for insert to authenticated
with check (user_id=(select auth.uid()) and private.is_workspace_member(workspace_id));
drop policy if exists web_push_subscriptions_update_own on public.web_push_subscriptions;
create policy web_push_subscriptions_update_own on public.web_push_subscriptions
for update to authenticated
using (user_id=(select auth.uid()) and private.is_workspace_member(workspace_id))
with check (user_id=(select auth.uid()) and private.is_workspace_member(workspace_id));
drop policy if exists web_push_subscriptions_delete_own on public.web_push_subscriptions;
create policy web_push_subscriptions_delete_own on public.web_push_subscriptions
for delete to authenticated
using (user_id=(select auth.uid()) and private.is_workspace_member(workspace_id));

create table if not exists public.web_push_delivery_log (

create table if not exists public.web_push_server_config (
  id smallint primary key default 1 check (id=1),
  vapid_public_key text not null,
  vapid_public_jwk jsonb not null,
  vapid_private_jwk jsonb not null,
  vapid_subject text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.web_push_server_config enable row level security;
